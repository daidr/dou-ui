/// <reference lib="es2023.array" />
/**
 * Generate one component module per icon, the barrel and the metadata from
 * `icons/`. Each icon is a `<name>.json` (label, categories) plus one
 * `<name>.<variant>.svg` per variant it is drawn in.
 */
import { mkdir, readdir, rm } from 'node:fs/promises'
import { categories } from '../src/categories'
import type { IconMeta, IconVariant } from '../src/types'

const root = new URL('../', import.meta.url)
const source = new URL('icons/', root)
const outDir = new URL('src/generated/', root)

/** Suffix of the component name for each variant. The line set is the default. */
const variants: Record<IconVariant, string> = { stroke: '' }

const shapes: Record<string, string[]> = {
  path: ['d'],
  circle: ['cx', 'cy', 'r'],
  ellipse: ['cx', 'cy', 'rx', 'ry'],
  rect: ['x', 'y', 'width', 'height', 'rx', 'ry'],
  line: ['x1', 'y1', 'x2', 'y2'],
  polyline: ['points'],
  polygon: ['points'],
}

/** The attributes every source file must carry on its root, so it previews as drawn. */
const rootAttrs = {
  viewBox: '0 0 16 16',
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': '1.5',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
}

const pascal = (name: string) =>
  name.replace(/(^|-)([a-z0-9])/g, (_, __: string, char: string) => char.toUpperCase())

const errors: string[] = []
const fail = (file: string, message: string) => errors.push(`icons/${file}: ${message}`)

function parseAttrs(text: string): Record<string, string> {
  const attrs: Record<string, string> = {}
  for (const [, key, value] of text.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[key!] = value!
  return attrs
}

type Node = [string, Record<string, number | string>]

function parseSvg(file: string, svg: string): Node[] {
  const match = svg.trim().match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/)
  if (!match) {
    fail(file, 'not a single <svg> element')
    return []
  }
  const attrs = parseAttrs(match[1]!)
  for (const [key, value] of Object.entries(rootAttrs)) {
    if (attrs[key] !== value) fail(file, `<svg> needs ${key}="${value}"`)
  }
  const nodes: Node[] = []
  const rest = match[2]!.replace(/<(\w+)\b([^>]*?)\s*\/>/g, (_, tag: string, body: string) => {
    const allowed = shapes[tag]
    if (!allowed) {
      fail(file, `<${tag}> is not allowed; use ${Object.keys(shapes).join(', ')}`)
      return ''
    }
    const node: Node = [tag, {}]
    for (const [key, value] of Object.entries(parseAttrs(body))) {
      if (!allowed.includes(key))
        fail(file, `<${tag}> may not set ${key}; style comes from the root`)
      else node[1][key] = /^-?\d*\.?\d+$/.test(value) ? Number(value) : value
    }
    nodes.push(node)
    return ''
  })
  if (rest.trim()) fail(file, `unexpected content: ${rest.trim().slice(0, 40)}`)
  if (!nodes.length) fail(file, 'draws nothing')
  return nodes
}

const files = await readdir(source)
const names = files
  .filter((file) => file.endsWith('.json'))
  .map((file) => file.slice(0, -'.json'.length))
  .toSorted()

for (const file of files) {
  const name = file.split('.')[0]!
  if (!names.includes(name)) fail(file, `has no ${name}.json`)
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(name)) fail(file, 'names are kebab-case')
}

const meta: IconMeta[] = []
const modules: { name: string; component: string; code: string }[] = []

for (const name of names) {
  const info = (await Bun.file(new URL(`${name}.json`, source)).json()) as Partial<IconMeta>
  if (typeof info.label !== 'string' || !info.label.trim()) fail(`${name}.json`, 'needs a label')
  if (!Array.isArray(info.categories) || !info.categories.length) {
    fail(`${name}.json`, 'needs at least one category')
  }
  for (const category of info.categories ?? []) {
    if (!(category in categories)) fail(`${name}.json`, `unknown category "${category}"`)
  }

  let drawn = 0
  for (const [variant, suffix] of Object.entries(variants) as [IconVariant, string][]) {
    const file = `${name}.${variant}.svg`
    if (!files.includes(file)) continue
    drawn++
    const nodes = parseSvg(file, await Bun.file(new URL(file, source)).text())
    const component = `${pascal(name)}${suffix}Icon`
    meta.push({
      name,
      component,
      label: info.label!,
      categories: info.categories!,
      variant,
    })
    modules.push({
      name: `${name}${suffix ? `-${variant}` : ''}`,
      component,
      code: [
        '// Generated by scripts/gen.ts. Do not edit.',
        "import { createIcon } from '../../create-icon'",
        '',
        `/** ${info.label} · \`${name}\` */`,
        `export const ${component} = /* #__PURE__ */ createIcon(${JSON.stringify(name)}, ${JSON.stringify(nodes)})`,
        '',
      ].join('\n'),
    })
  }
  if (!drawn) fail(`${name}.json`, `has no ${name}.<variant>.svg`)
}

if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

await rm(outDir, { recursive: true, force: true })
await mkdir(new URL('icons/', outDir), { recursive: true })
for (const module of modules) {
  await Bun.write(new URL(`icons/${module.name}.ts`, outDir), module.code)
}
await Bun.write(
  new URL('index.ts', outDir),
  [
    '// Generated by scripts/gen.ts. Do not edit.',
    ...modules.map((m) => `export { ${m.component} } from './icons/${m.name}'`),
    '',
  ].join('\n'),
)
await Bun.write(
  new URL('meta.ts', outDir),
  [
    '// Generated by scripts/gen.ts. Do not edit.',
    "import type { IconMeta } from '../types'",
    '',
    `export const icons: IconMeta[] = ${JSON.stringify(meta, null, 2)}`,
    '',
  ].join('\n'),
)
