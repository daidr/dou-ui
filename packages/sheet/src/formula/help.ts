/**
 * What a function takes and does, for completion and the argument hint
 * while typing a formula. `args` are the argument names in order:
 * `[name]` may be left out, and `…` means the one before can repeat.
 */
export interface SheetFunctionHelp {
  args: string[]
  description: string
}

type HelpTable = Record<string, [args: string, description: string]>

const read = (table: HelpTable): Record<string, SheetFunctionHelp> => {
  const out: Record<string, SheetFunctionHelp> = {}
  for (const [name, [args, description]] of Object.entries(table))
    out[name] = { args: args ? args.split(', ') : [], description }
  return out
}

